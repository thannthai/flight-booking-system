COMMENT ON COLUMN flights.source          IS 'Nguồn gốc tạo ra bản ghi';
COMMENT ON COLUMN airlines.code           IS 'Mã định danh quốc tế của hãng hàng không';
COMMENT ON COLUMN airlines.extra_baggage_fee IS 'Đơn giá tính tiền cho mỗi kg hành lý ký gửi khách mua thêm';
COMMENT ON COLUMN airports.iata_code      IS 'Mã 3 chữ số tiêu chuẩn quốc tế của sân bay (VD: SGN, HAN)';
COMMENT ON COLUMN aircrafts.model         IS 'Dòng máy bay (VD: Airbus A321, Boeing 787)';
COMMENT ON COLUMN booking.pnr            IS 'Mã đặt chỗ gồm 6-8 ký tự in hoa';
COMMENT ON COLUMN vouchers.version        IS 'Trường kỹ thuật dùng cho Optimistic Locking của JPA';
COMMENT ON COLUMN payments.provider_txn_id IS 'Transaction ID do cổng thanh toán sinh ra';
COMMENT ON COLUMN payments.callback_data  IS 'Chuỗi JSON thô thu được từ cổng thanh toán';
COMMENT ON COLUMN audit_logs.before_value IS 'Ảnh chụp dữ liệu trước khi Admin sửa';
COMMENT ON COLUMN audit_logs.after_value  IS 'Ảnh chụp dữ liệu sau khi Admin sửa thành công';

-- 1. Tìm kiếm chuyến bay
CREATE INDEX idx_flights_search       ON flights       (origin_iata_id, dest_iata_id, departure_time);
-- 2. Kiểm tra trạng thái ghế
CREATE INDEX idx_flight_seats_status  ON flight_seats  (flight_id, status);
-- 3. Giải phóng ghế held đã hết hạn
CREATE INDEX idx_flight_seats_held    ON flight_seats  (held_until) WHERE status = 'HELD';
-- 4. JOIN BOOKING ↔ USERS
CREATE INDEX idx_booking_user_id      ON booking       (user_id);
-- 5. JOIN TICKETS ↔ BOOKING
CREATE INDEX idx_tickets_booking_id   ON tickets       (booking_id);
-- 6. Quét đơn quá hạn chưa thanh toán
CREATE INDEX idx_booking_reminder     ON booking       (created_at) WHERE status = 'PENDING' AND reminder_sent = FALSE;