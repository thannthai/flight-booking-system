CREATE SCHEMA IF NOT EXISTS public;
SET search_path TO public;

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(255) NOT NULL,
    phone         VARCHAR(20)  NOT NULL UNIQUE,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('ROLE_USER', 'ROLE_ADMIN')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ
);

CREATE TABLE passengers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    full_name     VARCHAR(255) NOT NULL,
    date_of_birth DATE         NOT NULL,
    gender        VARCHAR(10)  NOT NULL CHECK (gender IN ('MALE', 'FEMALE')),
    nationality   VARCHAR(100),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ
);

CREATE TABLE passenger_documents (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id    BIGINT      NOT NULL,
    identity_type   VARCHAR(20) NOT NULL CHECK (identity_type IN ('CCCD', 'PASSPORT')),
    identity_number VARCHAR(50) NOT NULL UNIQUE,
    identity_expiry DATE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ
);

CREATE TABLE airlines (
    id                BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(10)    NOT NULL UNIQUE,
    name              VARCHAR(255)   NOT NULL,
    logo_url          VARCHAR(500),
    free_baggage      BOOLEAN        NOT NULL DEFAULT FALSE,
    extra_baggage_fee NUMERIC(10, 2) NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ
);

CREATE TABLE airports (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iata_code  VARCHAR(10)  NOT NULL UNIQUE,
    name       VARCHAR(255) NOT NULL,
    city       VARCHAR(100) NOT NULL,
    country    VARCHAR(100) NOT NULL,
    latitude   NUMERIC(9, 6),
    longitude  NUMERIC(9, 6),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE aircrafts (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airline_code_id BIGINT       NOT NULL,
    model           VARCHAR(100) NOT NULL,
    total_seats     INTEGER      NOT NULL,
    business_seats  INTEGER      NOT NULL DEFAULT 0,
    economy_seats   INTEGER      NOT NULL,
    registration_no VARCHAR(20)  NOT NULL UNIQUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ
);

CREATE TABLE flights (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_no       VARCHAR(10)    NOT NULL,
    airline_code_id BIGINT         NOT NULL,
    aircraft_id     BIGINT         NOT NULL,
    origin_iata_id  BIGINT         NOT NULL,
    dest_iata_id    BIGINT         NOT NULL,
    departure_time  TIMESTAMPTZ    NOT NULL,
    arrival_time    TIMESTAMPTZ    NOT NULL,
    status          VARCHAR(20)    NOT NULL DEFAULT 'SCHEDULED'
                        CHECK (status IN ('SCHEDULED', 'DELAYED', 'CANCELLED', 'COMPLETED')),
    base_price      NUMERIC(12, 2) NOT NULL,
    source          VARCHAR(20)    NOT NULL CHECK (source IN ('MANUAL', 'CRAWLER')),
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ
);

CREATE TABLE flight_seats (
    id           BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id    BIGINT         NOT NULL,
    seat_no      VARCHAR(10)    NOT NULL,
    cabin_class  VARCHAR(20)    NOT NULL CHECK (cabin_class IN ('ECONOMY', 'BUSINESS')),
    status       VARCHAR(20)    NOT NULL DEFAULT 'AVAILABLE'
                     CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED')),
    price        NUMERIC(12, 2) NOT NULL,
    held_until   TIMESTAMPTZ,
    held_by_user BIGINT,
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ
);

CREATE TABLE vouchers (
    id            BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(50)    NOT NULL UNIQUE,
    discount_type VARCHAR(20)    NOT NULL CHECK (discount_type IN ('PERCENT', 'FIXED')),
    value         NUMERIC(12, 2) NOT NULL,
    usage_limit   INTEGER        NOT NULL,
    used_count    INTEGER        NOT NULL DEFAULT 0,
    conditions    JSONB,
    valid_from    DATE           NOT NULL,
    valid_until   DATE           NOT NULL,
    version       INTEGER        NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ
);

CREATE TABLE booking (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pnr             VARCHAR(20)    NOT NULL UNIQUE,
    user_id         BIGINT         NOT NULL,
    trip_type       VARCHAR(20)    NOT NULL CHECK (trip_type IN ('ONE_WAY', 'ROUND_TRIP')),
    base_amount     NUMERIC(12, 2) NOT NULL,
    tax_amount      NUMERIC(12, 2) NOT NULL,
    discount_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total_amount    NUMERIC(12, 2) NOT NULL,
    status          VARCHAR(20)    NOT NULL DEFAULT 'PENDING'
                        CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED', 'PENDING_CANCEL', 'REFUNDED')),
    cancel_reason   TEXT,
    cancelled_by    BIGINT,
    cancelled_at    TIMESTAMPTZ,
    voucher_id      BIGINT,
    reminder_sent   BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ
);

CREATE TABLE booking_legs (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT      NOT NULL,
    flight_id  BIGINT      NOT NULL,
    leg_order  INTEGER     NOT NULL,
    direction  VARCHAR(20) NOT NULL CHECK (direction IN ('OUTBOUND', 'RETURN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE tickets (
    id             BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     BIGINT         NOT NULL,
    booking_leg_id BIGINT         NOT NULL,
    passenger_id   BIGINT         NOT NULL,
    flight_seat_id BIGINT,
    ticket_no      VARCHAR(50),
    passenger_type VARCHAR(20)    NOT NULL CHECK (passenger_type IN ('ADULT', 'CHILD', 'INFANT')),
    price          NUMERIC(12, 2) NOT NULL,
    status         VARCHAR(20)    NOT NULL DEFAULT 'PENDING'
                       CHECK (status IN ('PENDING', 'ISSUED', 'CANCELLED')),
    issued_at      TIMESTAMPTZ,
    created_at     TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ
);

CREATE TABLE add_on_services (
    id           BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id    BIGINT         NOT NULL,
    service_type VARCHAR(50)    NOT NULL CHECK (service_type IN ('BAGGAGE', 'INSURANCE', 'MEAL')),
    description  VARCHAR(255)   NOT NULL,
    price        NUMERIC(12, 2) NOT NULL,
    quantity     INTEGER        NOT NULL DEFAULT 1,
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ
);

CREATE TABLE payments (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      BIGINT         NOT NULL,
    provider        VARCHAR(20)    NOT NULL CHECK (provider IN ('STRIPE', 'VNPAY', 'SEPAY')),
    provider_txn_id VARCHAR(255)   UNIQUE,
    amount          NUMERIC(12, 2) NOT NULL,
    currency        VARCHAR(10)    NOT NULL DEFAULT 'VND',
    status          VARCHAR(20)    NOT NULL DEFAULT 'PENDING'
                        CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    callback_data   TEXT,
    paid_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ
);

CREATE TABLE notifications (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      BIGINT       NOT NULL,
    user_id         BIGINT       NOT NULL,
    type            VARCHAR(50)  NOT NULL
                        CHECK (type IN ('BOOKING_CONFIRM', 'TICKET_ISSUED', 'PAYMENT_REMINDER',
                                        'FLIGHT_DELAYED', 'FLIGHT_CANCELLED', 'REFUND_CONFIRMATION')),
    recipient_email VARCHAR(255) NOT NULL,
    status          VARCHAR(20)  NOT NULL CHECK (status IN ('SENT', 'FAILED')),
    error_message   TEXT,
    sent_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ
);

CREATE TABLE audit_logs (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id     BIGINT        NOT NULL,
    entity_type  VARCHAR(50)   NOT NULL,
    entity_id    BIGINT        NOT NULL,
    action       VARCHAR(50)   NOT NULL CHECK (action IN ('CANCEL', 'REFUND', 'UPDATE', 'DELETE')),
    before_value JSONB,
    after_value  JSONB,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ
);

-- Foreign Keys
ALTER TABLE passengers       ADD CONSTRAINT fk_passengers_user_id         FOREIGN KEY (user_id)       REFERENCES users (id);
ALTER TABLE passenger_documents ADD CONSTRAINT fk_passenger_docs_passenger_id FOREIGN KEY (passenger_id)  REFERENCES passengers (id);
ALTER TABLE aircrafts        ADD CONSTRAINT fk_aircrafts_airline_id        FOREIGN KEY (airline_code_id) REFERENCES airlines (id);
ALTER TABLE flights           ADD CONSTRAINT fk_flights_airline_id          FOREIGN KEY (airline_code_id) REFERENCES airlines (id);
ALTER TABLE flights           ADD CONSTRAINT fk_flights_aircraft_id         FOREIGN KEY (aircraft_id)    REFERENCES aircrafts (id);
ALTER TABLE flights           ADD CONSTRAINT fk_flights_origin_id           FOREIGN KEY (origin_iata_id) REFERENCES airports (id);
ALTER TABLE flights           ADD CONSTRAINT fk_flights_dest_id             FOREIGN KEY (dest_iata_id)   REFERENCES airports (id);
ALTER TABLE flight_seats      ADD CONSTRAINT fk_flight_seats_flight_id      FOREIGN KEY (flight_id)      REFERENCES flights (id);
ALTER TABLE flight_seats      ADD CONSTRAINT fk_flight_seats_held_by_user   FOREIGN KEY (held_by_user)   REFERENCES users (id);
ALTER TABLE booking           ADD CONSTRAINT fk_booking_user_id             FOREIGN KEY (user_id)        REFERENCES users (id);
ALTER TABLE booking           ADD CONSTRAINT fk_booking_cancelled_by        FOREIGN KEY (cancelled_by)   REFERENCES users (id);
ALTER TABLE booking           ADD CONSTRAINT fk_booking_voucher_id          FOREIGN KEY (voucher_id)     REFERENCES vouchers (id);
ALTER TABLE booking_legs      ADD CONSTRAINT fk_booking_legs_booking_id     FOREIGN KEY (booking_id)     REFERENCES booking (id);
ALTER TABLE booking_legs      ADD CONSTRAINT fk_booking_legs_flight_id      FOREIGN KEY (flight_id)      REFERENCES flights (id);
ALTER TABLE tickets           ADD CONSTRAINT fk_tickets_booking_id          FOREIGN KEY (booking_id)     REFERENCES booking (id);
ALTER TABLE tickets           ADD CONSTRAINT fk_tickets_booking_leg_id      FOREIGN KEY (booking_leg_id) REFERENCES booking_legs (id);
ALTER TABLE tickets           ADD CONSTRAINT fk_tickets_passenger_id        FOREIGN KEY (passenger_id)   REFERENCES passengers (id);
ALTER TABLE tickets           ADD CONSTRAINT fk_tickets_flight_seat_id      FOREIGN KEY (flight_seat_id) REFERENCES flight_seats (id);
ALTER TABLE add_on_services   ADD CONSTRAINT fk_addon_services_ticket_id    FOREIGN KEY (ticket_id)      REFERENCES tickets (id);
ALTER TABLE payments          ADD CONSTRAINT fk_payments_booking_id         FOREIGN KEY (booking_id)     REFERENCES booking (id);
ALTER TABLE notifications     ADD CONSTRAINT fk_notifications_booking_id    FOREIGN KEY (booking_id)     REFERENCES booking (id);
ALTER TABLE notifications     ADD CONSTRAINT fk_notifications_user_id       FOREIGN KEY (user_id)        REFERENCES users (id);
ALTER TABLE audit_logs        ADD CONSTRAINT fk_audit_logs_admin_id         FOREIGN KEY (admin_id)       REFERENCES users (id);

